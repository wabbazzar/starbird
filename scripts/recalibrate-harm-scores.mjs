// Phase 4 of docs/tickets/pending/harm-score-recalibration.md
//
// Clamps every stored firms[].harmScore into its scope's [floor, cap] band and
// writes an audit trail to docs/harm-score-recalibration-2026-09.md.
//
// Why write the clamped value back rather than only clamping at display time:
// the runner keeps producing uncapped scores, and Phase 6 makes the release
// battery FAIL on any firm outside its band. Storing the clamped number lets
// that gate be strict instead of advisory. firmEffectiveScore() still clamps
// at read time as defence in depth — after this pass it is a no-op on current
// data. Raw pre-clamp values live in git history and in the audit doc.
//
// NOTE: the ticket also planned a monotone rescale of the 2026-04 cohort to
// correct research-date drift. Measured after the cap/floor pass, per-month
// medians of harmful firms are 66-70 across all six cohorts (they were 60-79
// before). The drift was the narrow-vendor inflation, not a cohort artefact,
// so no rescale is applied — see the audit doc.
//
//   node scripts/recalibrate-harm-scores.mjs --dry-run
//   node scripts/recalibrate-harm-scores.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const DATA = new URL('../static/data.json', import.meta.url);
const DOC = new URL('../docs/harm-score-recalibration-2026-09.md', import.meta.url);
const DRY = process.argv.includes('--dry-run');

// Mirrors SCOPE_CAP / SCOPE_FLOOR in src/lib/ranking.ts.
const CAP = { narrow: 65, single_company: 79, multi_company: 94, systemic: 100 };
const FLOOR = { multi_company: 60, systemic: 70 };

const data = JSON.parse(readFileSync(DATA, 'utf8'));
const changes = [];
const missing = [];

for (const f of data.firms) {
	if (!f.scope) {
		missing.push(f.id);
		continue;
	}
	const cap = CAP[f.scope];
	const floor = FLOOR[f.scope] ?? 0;
	const next = Math.min(cap, Math.max(floor, f.harmScore));
	if (next === f.harmScore) continue;
	changes.push({
		id: f.id,
		name: f.name,
		scope: f.scope,
		role: f.role,
		from: f.harmScore,
		to: next,
		rule: next < f.harmScore ? `cap ${cap}` : `floor ${floor}`,
		addedAt: f.addedAt ?? ''
	});
	f.harmScore = next;
}

const capped = changes.filter((c) => c.to < c.from);
const floored = changes.filter((c) => c.to > c.from);

const median = (a) => {
	const s = [...a].sort((x, y) => x - y);
	return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const byMonth = new Map();
for (const f of data.firms) {
	// Aligned firms (the 5-9 band) are a different population; including them
	// makes the "harmful firm" median meaningless.
	if (f.harmScore < 20) continue;
	const m = (f.addedAt ?? 'unknown').slice(0, 7);
	if (!byMonth.has(m)) byMonth.set(m, []);
	byMonth.get(m).push(f.harmScore);
}
const cohorts = [...byMonth.entries()]
	.sort()
	.map(([m, v]) => ({ month: m, n: v.length, median: median(v) }));

console.log(`capped down: ${capped.length}   floored up: ${floored.length}`);
if (missing.length) console.error(`firms missing scope (skipped): ${missing.length}`, missing.slice(0, 10));
console.table(changes.sort((a, b) => b.from - a.from).slice(0, 40));
console.log('\nper-cohort median (harmful firms only) after recalibration:');
console.table(cohorts);
const spread = Math.max(...cohorts.map((c) => c.median)) - Math.min(...cohorts.map((c) => c.median));
console.log(`cohort median spread: ${spread} (ticket target: <= 5)`);

const doc = `# Harm score recalibration — 2026-09

Generated by \`scripts/recalibrate-harm-scores.mjs\`. Phase 4 of
\`docs/tickets/pending/harm-score-recalibration.md\`.

Every firm now carries a \`scope\`, which imposes a cap and (for the two wide
scopes) a floor on its harm score:

| scope | cap | floor |
|---|---|---|
| narrow | 65 | — |
| single_company | 79 | — |
| multi_company | 94 | 60 |
| systemic | 100 | 70 |

**${changes.length} of ${data.firms.length} firms moved** — ${capped.length} capped down,
${floored.length} floored up. Scores inside their band were left untouched: this
pass changes the *bounds* on the researched judgment, not the judgment.

## Cohort drift

The ticket planned a monotone rescale of the 2026-04 cohort, whose median
(60) sat far below 2026-07's (79). Measured after the cap/floor pass, that gap
is gone on its own — the inflation was single-contract vendors scoring 78-90,
which the \`narrow\` cap now bounds at 65.

| cohort | n | median |
|---|---|---|
${cohorts.map((c) => `| ${c.month} | ${c.n} | ${c.median} |`).join('\n')}

Spread: **${spread} points** (ticket target: ≤ 5). No rescale applied.

## Capped down (${capped.length})

| firm | scope | from | to | rule | added |
|---|---|---|---|---|---|
${capped
	.sort((a, b) => b.from - a.from)
	.map((c) => `| ${c.name} | ${c.scope} | ${c.from} | ${c.to} | ${c.rule} | ${c.addedAt} |`)
	.join('\n')}

## Floored up (${floored.length})

| firm | scope | from | to | rule | added |
|---|---|---|---|---|---|
${floored
	.sort((a, b) => a.from - b.from)
	.map((c) => `| ${c.name} | ${c.scope} | ${c.from} | ${c.to} | ${c.rule} | ${c.addedAt} |`)
	.join('\n')}
`;

if (DRY) {
	console.log('\n--dry-run: nothing written');
} else {
	writeFileSync(DATA, JSON.stringify(data, null, '\t') + '\n');
	writeFileSync(DOC, doc);
	console.log('\nwrote static/data.json + docs/harm-score-recalibration-2026-09.md');
}
